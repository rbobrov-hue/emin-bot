# Верхние границы: очень низкий, низкий, средний, высокий; выше — очень высокий
NORMS = {
 "МП":(19,22,26,30), "МУ":(14,17,21,24), "ВП":(13,16,21,25), "ВУ":(9,12,15,17),
 "ВЭ":(6,9,12,15), "МЭИ":(34,39,46,52), "ВЭИ":(33,38,47,54),
 "ПЭ":(34,39,47,53), "УЭ":(33,39,47,53), "ОЭИ":(71,78,92,104),
}
LEVELS = ["очень низкий", "низкий", "средний", "высокий", "очень высокий"]

def level(scale, score):
    for i, b in enumerate(NORMS[scale]):
        if score <= b:
            return LEVELS[i]
    return LEVELS[4]

def score(answers):
    """answers: список из 46 значений 0..3 (индекс варианта ответа)."""
    assert len(answers) == len(ITEMS)
    s = {k: 0 for k in ("МП","МУ","ВП","ВУ","ВЭ")}
    for (_, sub, direct), a in zip(ITEMS, answers):
        s[sub] += a if direct else 3 - a
    s["МЭИ"] = s["МП"] + s["МУ"]
    s["ВЭИ"] = s["ВП"] + s["ВУ"] + s["ВЭ"]
    s["ПЭ"] = s["МП"] + s["ВП"]
    s["УЭ"] = s["МУ"] + s["ВУ"] + s["ВЭ"]
    s["ОЭИ"] = s["МЭИ"] + s["ВЭИ"]
    return s
